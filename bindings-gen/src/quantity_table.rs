//! Emits `desktop/web/src/generated/quantity-table.ts` from
//! `canopi_types::quantity` (contracts §14, F35, `2.1-Q120`, `2.1-Q133`,
//! `2.1-Q169`, `2.1-Q356`).

use std::error::Error;
use std::fmt::Write;

use canopi_types::quantity::{
    CONVERSION_CONSTANTS, DisplayBand, DisplayStyle, PDF_SCALES, PdfScaleSpec, QUANTITIES,
    QuantityKind, QuantitySpec, QuantitySystemSpec, SCALE_BAR_STEPS_METRIC_M, SCALE_BAR_STEPS_US_M,
    US_CUSTOMARY_REGIONS, UnitId, UnitInputSpec, UnitSystem,
};

pub(crate) fn render_quantity_table_ts() -> Result<String, Box<dyn Error>> {
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by `cargo run -p bindings-gen` from `canopi-types/src/quantity.rs`."
    )?;
    writeln!(out, "// Do not edit by hand.")?;
    writeln!(out)?;
    write_types(&mut out)?;
    write_regions_and_constants(&mut out)?;
    write_units(&mut out)?;
    write_quantities(&mut out)?;
    write_pdf_scales(&mut out)?;
    write_scale_bar_steps(&mut out)?;
    Ok(out)
}

fn write_types(out: &mut String) -> Result<(), Box<dyn Error>> {
    let systems = UnitSystem::ALL
        .iter()
        .map(|s| format!("'{}'", s.as_str()))
        .collect::<Vec<_>>()
        .join(" | ");
    writeln!(out, "export type UnitSystem = {systems}")?;
    let kinds = QuantityKind::ALL
        .iter()
        .map(|k| format!("'{}'", k.as_str()))
        .collect::<Vec<_>>()
        .join(" | ");
    writeln!(out, "export type QuantityKind = {kinds}")?;
    let units = UnitId::ALL
        .iter()
        .map(|u| format!("'{}'", u.as_str()))
        .collect::<Vec<_>>()
        .join(" | ");
    writeln!(out, "export type UnitId = {units}")?;
    writeln!(
        out,
        "export type PdfScaleGroup = 'fit' | 'ratio' | 'us_architectural' | 'us_engineering'"
    )?;
    writeln!(out)?;
    writeln!(out, "export interface UnitMeta {{")?;
    writeln!(out, "  readonly id: UnitId")?;
    writeln!(out, "  readonly intlUnit: string | null")?;
    writeln!(out, "  readonly symbol: string")?;
    writeln!(out, "}}")?;
    writeln!(out)?;
    writeln!(out, "export type DisplayStyle =")?;
    writeln!(
        out,
        "  | {{ readonly kind: 'single'; readonly unit: UnitId; readonly decimals: number }}"
    )?;
    writeln!(
        out,
        "  | {{ readonly kind: 'feet_and_inches'; readonly dropZeroInches: boolean }}"
    )?;
    writeln!(out)?;
    writeln!(out, "export interface DisplayBand {{")?;
    writeln!(out, "  readonly maxSiExclusive: number | null")?;
    writeln!(out, "  readonly style: DisplayStyle")?;
    writeln!(out, "}}")?;
    writeln!(out)?;
    writeln!(out, "export interface UnitInputSpec {{")?;
    writeln!(out, "  readonly unit: UnitId")?;
    writeln!(out, "  readonly siPerUnit: number")?;
    writeln!(out, "  readonly offsetInUnit: number")?;
    writeln!(out, "  readonly aliases: readonly string[]")?;
    writeln!(out, "}}")?;
    writeln!(out)?;
    writeln!(out, "export interface QuantitySystemSpec {{")?;
    writeln!(out, "  readonly bareInputUnit: UnitId")?;
    writeln!(out, "  readonly bands: readonly DisplayBand[]")?;
    writeln!(out, "}}")?;
    writeln!(out)?;
    writeln!(out, "export interface QuantitySpec {{")?;
    writeln!(out, "  readonly kind: QuantityKind")?;
    writeln!(out, "  readonly siUnit: UnitId")?;
    writeln!(out, "  readonly allowsNegative: boolean")?;
    writeln!(out, "  readonly acceptsFeetAndInches: boolean")?;
    writeln!(out, "  readonly approximatePrefix: boolean")?;
    writeln!(out, "  readonly wholeSourceRoundsToWholeUnit: boolean")?;
    writeln!(out, "  readonly metric: QuantitySystemSpec")?;
    writeln!(out, "  readonly usCustomary: QuantitySystemSpec")?;
    writeln!(out, "  readonly inputUnits: readonly UnitInputSpec[]")?;
    writeln!(out, "}}")?;
    writeln!(out)?;
    writeln!(out, "export interface PdfScaleSpec {{")?;
    writeln!(out, "  readonly id: string")?;
    writeln!(out, "  readonly group: Exclude<PdfScaleGroup, 'fit'>")?;
    writeln!(out, "  readonly label: string | null")?;
    writeln!(out, "  readonly denominator: number")?;
    writeln!(out, "  readonly metric: boolean")?;
    writeln!(out, "  readonly usCustomary: boolean")?;
    writeln!(out, "}}")?;
    writeln!(out)?;
    Ok(())
}

fn write_regions_and_constants(out: &mut String) -> Result<(), Box<dyn Error>> {
    let regions = US_CUSTOMARY_REGIONS
        .iter()
        .map(|code| format!("'{code}'"))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(
        out,
        "export const US_CUSTOMARY_REGIONS: readonly string[] = [{regions}] as const"
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "export function defaultUnitSystemForRegion(region: string | null | undefined): UnitSystem {{"
    )?;
    writeln!(out, "  const code = region?.trim().toUpperCase() ?? ''")?;
    writeln!(
        out,
        "  return US_CUSTOMARY_REGIONS.includes(code) ? 'us_customary' : 'metric'"
    )?;
    writeln!(out, "}}")?;
    writeln!(out)?;
    let c = &CONVERSION_CONSTANTS;
    writeln!(out, "export const CONVERSION_CONSTANTS = {{")?;
    writeln!(out, "  mPerMm: {},", fmt_f64(c.m_per_mm))?;
    writeln!(out, "  mPerCm: {},", fmt_f64(c.m_per_cm))?;
    writeln!(out, "  mPerKm: {},", fmt_f64(c.m_per_km))?;
    writeln!(out, "  mPerInch: {},", fmt_f64(c.m_per_inch))?;
    writeln!(out, "  inchesPerFoot: {},", fmt_f64(c.inches_per_foot))?;
    writeln!(out, "  mPerFoot: {},", fmt_f64(c.m_per_foot))?;
    writeln!(out, "  feetPerMile: {},", fmt_f64(c.feet_per_mile))?;
    writeln!(out, "  mPerMile: {},", fmt_f64(c.m_per_mile))?;
    writeln!(out, "  m2PerCm2: {},", fmt_f64(c.m2_per_cm2))?;
    writeln!(out, "  m2PerHectare: {},", fmt_f64(c.m2_per_hectare))?;
    writeln!(out, "  m2PerKm2: {},", fmt_f64(c.m2_per_km2))?;
    writeln!(out, "  m2PerSqInch: {},", fmt_f64(c.m2_per_sq_inch))?;
    writeln!(out, "  m2PerSqFoot: {},", fmt_f64(c.m2_per_sq_foot))?;
    writeln!(out, "  sqFeetPerAcre: {},", fmt_f64(c.sq_feet_per_acre))?;
    writeln!(out, "  m2PerAcre: {},", fmt_f64(c.m2_per_acre))?;
    writeln!(out, "  mmPerCm: {},", fmt_f64(c.mm_per_cm))?;
    writeln!(out, "  mmPerInch: {},", fmt_f64(c.mm_per_inch))?;
    writeln!(out, "  litersPerMl: {},", fmt_f64(c.liters_per_ml))?;
    writeln!(
        out,
        "  litersPerUsGallon: {},",
        fmt_f64(c.liters_per_us_gallon)
    )?;
    writeln!(out, "  fahrenheitScale: {},", fmt_f64(c.fahrenheit_scale))?;
    writeln!(out, "  fahrenheitOffset: {},", fmt_f64(c.fahrenheit_offset))?;
    writeln!(out, "}} as const")?;
    writeln!(out)?;
    Ok(())
}

fn write_units(out: &mut String) -> Result<(), Box<dyn Error>> {
    writeln!(
        out,
        "export const UNIT_META: Readonly<Record<UnitId, UnitMeta>> = {{"
    )?;
    for &unit in UnitId::ALL {
        let intl = match unit.intl_unit() {
            Some(name) => format!("'{name}'"),
            None => "null".to_string(),
        };
        let symbol = serde_json::to_string(unit.symbol())?;
        writeln!(
            out,
            "  '{}': {{ id: '{}', intlUnit: {intl}, symbol: {symbol} }},",
            unit.as_str(),
            unit.as_str()
        )?;
    }
    writeln!(out, "}} as const")?;
    writeln!(out)?;
    Ok(())
}

fn write_quantities(out: &mut String) -> Result<(), Box<dyn Error>> {
    writeln!(
        out,
        "export const QUANTITY_TABLE: Readonly<Record<QuantityKind, QuantitySpec>> = {{"
    )?;
    for spec in QUANTITIES {
        write_quantity_spec(out, spec)?;
    }
    writeln!(out, "}} as const")?;
    writeln!(out)?;
    Ok(())
}

fn write_quantity_spec(out: &mut String, spec: &QuantitySpec) -> Result<(), Box<dyn Error>> {
    writeln!(out, "  '{}': {{", spec.kind.as_str())?;
    writeln!(out, "    kind: '{}',", spec.kind.as_str())?;
    writeln!(out, "    siUnit: '{}',", spec.si_unit.as_str())?;
    writeln!(out, "    allowsNegative: {},", spec.allows_negative)?;
    writeln!(
        out,
        "    acceptsFeetAndInches: {},",
        spec.accepts_feet_and_inches
    )?;
    writeln!(out, "    approximatePrefix: {},", spec.approximate_prefix)?;
    writeln!(
        out,
        "    wholeSourceRoundsToWholeUnit: {},",
        spec.whole_source_rounds_to_whole_unit
    )?;
    write_system_spec(out, "metric", &spec.metric)?;
    write_system_spec(out, "usCustomary", &spec.us_customary)?;
    writeln!(out, "    inputUnits: [")?;
    for input in spec.input_units {
        write_input_unit(out, input)?;
    }
    writeln!(out, "    ],")?;
    writeln!(out, "  }},")?;
    Ok(())
}

fn write_system_spec(
    out: &mut String,
    key: &str,
    spec: &QuantitySystemSpec,
) -> Result<(), Box<dyn Error>> {
    writeln!(
        out,
        "    {key}: {{ bareInputUnit: '{}', bands: [",
        spec.bare_input_unit.as_str()
    )?;
    for band in spec.bands {
        write_band(out, band)?;
    }
    writeln!(out, "    ] }},")?;
    Ok(())
}

fn write_band(out: &mut String, band: &DisplayBand) -> Result<(), Box<dyn Error>> {
    let max = match band.max_si_exclusive {
        Some(limit) => fmt_f64(limit),
        None => "null".to_string(),
    };
    let style = match band.style {
        DisplayStyle::Single { unit, decimals } => format!(
            "{{ kind: 'single', unit: '{}', decimals: {decimals} }}",
            unit.as_str()
        ),
        DisplayStyle::FeetAndInches { drop_zero_inches } => {
            format!("{{ kind: 'feet_and_inches', dropZeroInches: {drop_zero_inches} }}")
        }
    };
    writeln!(out, "      {{ maxSiExclusive: {max}, style: {style} }},")?;
    Ok(())
}

fn write_input_unit(out: &mut String, input: &UnitInputSpec) -> Result<(), Box<dyn Error>> {
    let aliases = input
        .aliases
        .iter()
        .map(serde_json::to_string)
        .collect::<Result<Vec<_>, _>>()?
        .join(", ");
    writeln!(
        out,
        "      {{ unit: '{}', siPerUnit: {}, offsetInUnit: {}, aliases: [{aliases}] }},",
        input.unit.as_str(),
        fmt_f64(input.si_per_unit),
        fmt_f64(input.offset_in_unit)
    )?;
    Ok(())
}

fn write_pdf_scales(out: &mut String) -> Result<(), Box<dyn Error>> {
    writeln!(out, "export const PDF_SCALES: readonly PdfScaleSpec[] = [")?;
    for scale in PDF_SCALES {
        write_pdf_scale(out, scale)?;
    }
    writeln!(out, "] as const")?;
    writeln!(out)?;
    Ok(())
}

fn write_pdf_scale(out: &mut String, scale: &PdfScaleSpec) -> Result<(), Box<dyn Error>> {
    let label = match scale.label {
        Some(text) => serde_json::to_string(text)?,
        None => "null".to_string(),
    };
    writeln!(
        out,
        "  {{ id: '{}', group: '{}', label: {label}, denominator: {}, metric: {}, usCustomary: {} }},",
        scale.id,
        scale.group.as_str(),
        scale.denominator,
        scale.metric,
        scale.us_customary
    )?;
    Ok(())
}

fn write_scale_bar_steps(out: &mut String) -> Result<(), Box<dyn Error>> {
    let metric = SCALE_BAR_STEPS_METRIC_M
        .iter()
        .map(|&v| fmt_f64(v))
        .collect::<Vec<_>>()
        .join(", ");
    let us = SCALE_BAR_STEPS_US_M
        .iter()
        .map(|&v| fmt_f64(v))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(
        out,
        "export const SCALE_BAR_STEPS_M: Readonly<Record<UnitSystem, readonly number[]>> = {{"
    )?;
    writeln!(out, "  metric: [{metric}],")?;
    writeln!(out, "  us_customary: [{us}],")?;
    writeln!(out, "}} as const")?;
    Ok(())
}

fn fmt_f64(value: f64) -> String {
    if value.fract() == 0.0 && value.abs() < 1e15 {
        format!("{}", value as i64)
    } else {
        format!("{value}")
    }
}

#[cfg(test)]
mod tests {
    use super::render_quantity_table_ts;

    #[test]
    fn quantity_table_ts_renders_deterministically_with_approved_tables() {
        let first = render_quantity_table_ts().expect("renders quantity table TS");
        let second = render_quantity_table_ts().expect("renders deterministically");
        assert_eq!(first, second);
        assert!(first.contains("US_CUSTOMARY_REGIONS: readonly string[] = ['US', 'LR', 'MM']"));
        assert!(first.contains("dropZeroInches: true"));
        assert!(first.contains("approximatePrefix: false"));
        assert!(first.contains("wholeSourceRoundsToWholeUnit: true"));
        assert!(first.contains("wholeSourceRoundsToWholeUnit: false"));
        assert!(first.contains("mmPerCm: 10"));
        assert!(first.contains("litersPerMl: 0.001"));
        assert!(first.contains("id: 'ratio:5000', group: 'ratio', label: null, denominator: 5000"));
        assert!(first.contains("id: 'us_arch:1_8_in_1_ft'"));
        assert!(first.contains("id: 'us_eng:1_in_100_ft'"));
        // Metric 1500 m (#316 nit: de-DE "1,50 km") falls in the >= 1000 m km/2-decimal band.
        assert!(
            first.contains(
                "maxSiExclusive: 1000, style: { kind: 'single', unit: 'm', decimals: 0 }"
            )
        );
        assert!(
            first.contains(
                "maxSiExclusive: null, style: { kind: 'single', unit: 'km', decimals: 2 }"
            )
        );
    }
}
