//! The `LocaleKey` union (2.1-Q211): every key of the English interface strings, so `t` refuses a key English lacks
//! at typecheck time. English is the source locale: the other ten locales are checked against it by
//! `i18n-completeness.test.ts`, so a key here exists in all eleven.

use serde_json::Value;
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

/// The English interface strings, relative to the source root.
pub(crate) const EN_JSON: &str = "desktop/web/src/i18n/en.json";

/// i18next's plural categories (`Intl.PluralRules`): `t('items', { count })` resolves `items_one` and its siblings,
/// so a suffixed key also yields its base key.
const PLURAL_SUFFIXES: [&str; 6] = ["_zero", "_one", "_two", "_few", "_many", "_other"];

/// Renders `export type LocaleKey = ...` from en.json at `en_json`: nested objects become dot keys, each plural key
/// adds its base key, sorted and deduplicated. A value that is no string or object is refused, naming its key.
pub(crate) fn render_locale_keys(en_json: &Path) -> Result<String, Box<dyn std::error::Error>> {
    let text = std::fs::read_to_string(en_json)
        .map_err(|error| format!("failed to read {}: {error}", en_json.display()))?;
    let root: Value = serde_json::from_str(&text)
        .map_err(|error| format!("failed to parse {}: {error}", en_json.display()))?;
    let mut keys = BTreeSet::new();
    collect_keys(&root, "", &mut keys)
        .map_err(|error| format!("{}: {error}", en_json.display()))?;
    let mut output = format!(
        "// Generated by `cargo run -p bindings-gen` from {EN_JSON}. Do not edit by hand.\n\nexport type LocaleKey ="
    );
    if keys.is_empty() {
        output.push_str(" never\n");
    } else {
        output.push('\n');
        for key in &keys {
            writeln!(output, "  | {}", serde_json::to_string(key)?)?;
        }
    }
    Ok(output)
}

fn collect_keys(value: &Value, prefix: &str, keys: &mut BTreeSet<String>) -> Result<(), String> {
    match value {
        Value::Object(entries) => {
            for (name, child) in entries {
                let key = if prefix.is_empty() {
                    name.clone()
                } else {
                    format!("{prefix}.{name}")
                };
                collect_keys(child, &key, keys)?;
            }
            Ok(())
        }
        Value::String(_) if !prefix.is_empty() => {
            if let Some(base) = PLURAL_SUFFIXES
                .iter()
                .find_map(|suffix| prefix.strip_suffix(suffix))
                .filter(|base| !base.is_empty())
            {
                keys.insert(base.to_owned());
            }
            keys.insert(prefix.to_owned());
            Ok(())
        }
        _ => Err(format!(
            "the interface string {:?} is no string or object of strings",
            if prefix.is_empty() { "(root)" } else { prefix }
        )),
    }
}

#[cfg(test)]
mod tests {
    use super::render_locale_keys;
    use std::fs;
    use std::path::PathBuf;
    use std::sync::atomic::{AtomicU64, Ordering};

    static NEXT_FIXTURE: AtomicU64 = AtomicU64::new(0);

    struct Fixture(PathBuf);

    impl Fixture {
        fn en_json(contents: &str) -> Self {
            let dir = std::env::temp_dir().join(format!(
                "canopi_bindings_gen_locale_keys_{}_{}",
                std::process::id(),
                NEXT_FIXTURE.fetch_add(1, Ordering::Relaxed),
            ));
            fs::create_dir_all(&dir).unwrap();
            fs::write(dir.join("en.json"), contents).unwrap();
            Self(dir)
        }

        fn render(&self) -> String {
            render_locale_keys(&self.0.join("en.json")).unwrap()
        }
    }

    impl Drop for Fixture {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    fn members(rendered: &str) -> Vec<&str> {
        rendered
            .lines()
            .filter_map(|line| line.trim_start().strip_prefix("| "))
            .collect()
    }

    #[test]
    fn nested_objects_become_dot_keys() {
        let fixture = Fixture::en_json(
            r#"{"about": {"title": "About", "links": {"site": "Site"}}, "ok": "OK"}"#,
        );

        let rendered = fixture.render();

        assert!(rendered.starts_with("// Generated by `cargo run -p bindings-gen`"));
        assert!(rendered.contains("export type LocaleKey =\n"));
        assert_eq!(
            members(&rendered),
            [r#""about.links.site""#, r#""about.title""#, r#""ok""#]
        );
    }

    #[test]
    fn a_plural_suffixed_key_yields_its_base_key_too() {
        let fixture = Fixture::en_json(
            r#"{"n": {"items_zero": "z", "items_one": "o", "items_two": "t", "items_few": "f", "items_many": "m", "items_other": "x", "shown_other": "s", "overone": "w"}}"#,
        );

        let keys = members(&fixture.render())
            .into_iter()
            .map(str::to_owned)
            .collect::<Vec<_>>();

        for expected in [
            "n.items",
            "n.items_zero",
            "n.items_one",
            "n.items_two",
            "n.items_few",
            "n.items_many",
            "n.items_other",
            "n.shown",
            "n.shown_other",
            "n.overone",
        ] {
            assert!(
                keys.contains(&format!("\"{expected}\"")),
                "missing {expected} in {keys:?}"
            );
        }
        assert_eq!(keys.len(), 10, "no other key: {keys:?}");
    }

    #[test]
    fn keys_are_sorted_and_deduplicated() {
        let fixture = Fixture::en_json(
            r#"{"b": "B", "a": {"x_one": "1", "x_other": "2", "x": "plain", "y": "nested"}, "a.y": "dotted", "a2": {"y": "nested"}}"#,
        );

        assert_eq!(
            members(&fixture.render()),
            [
                r#""a.x""#,
                r#""a.x_one""#,
                r#""a.x_other""#,
                r#""a.y""#,
                r#""a2.y""#,
                r#""b""#,
            ]
        );
    }

    #[test]
    fn output_is_byte_identical_on_rerun() {
        let fixture = Fixture::en_json(r#"{"z": "Z", "a": {"b_one": "1", "b_other": "2"}}"#);

        assert_eq!(fixture.render().into_bytes(), fixture.render().into_bytes());
        assert_eq!(
            fixture.render(),
            "// Generated by `cargo run -p bindings-gen` from desktop/web/src/i18n/en.json. Do not edit by hand.\n\n\
             export type LocaleKey =\n  | \"a.b\"\n  | \"a.b_one\"\n  | \"a.b_other\"\n  | \"z\"\n"
        );
    }

    #[test]
    fn a_key_that_is_no_string_is_refused_with_its_name() {
        let fixture = Fixture::en_json(r#"{"menu": {"items": ["one", "two"]}}"#);

        let error = render_locale_keys(&fixture.0.join("en.json")).unwrap_err();

        assert!(error.to_string().contains("menu.items"), "{error}");
    }
}
