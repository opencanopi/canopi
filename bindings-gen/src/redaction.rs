//! The redaction table (`canopi-types/redaction.json`; contracts §13, ADR 0025
//! Redaction, 2.1-M434) emitted to both redactors: the credential names, the
//! known file extensions and the tokens, as `desktop/web/src/generated/redaction.ts` for
//! `failures/redact.ts` and `canopi-redact/src/table_generated.rs` for
//! `canopi-redact`, so neither language keeps its own list.

use serde::Deserialize;
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

pub(crate) const REDACTION_JSON: &str = "canopi-types/redaction.json";

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct RedactionTable {
    #[serde(rename = "$comment")]
    _comment: String,
    version: u32,
    credential_names: Vec<String>,
    known_extensions: Vec<String>,
    tokens: Tokens,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Tokens {
    redacted: String,
    path: String,
}

/// The rendered table: (TypeScript, unformatted Rust).
pub(crate) fn render_redaction_table(
    path: &Path,
) -> Result<(String, String), Box<dyn std::error::Error>> {
    let table: RedactionTable = serde_json::from_str(&std::fs::read_to_string(path)?)
        .map_err(|error| format!("{REDACTION_JSON}: {error}"))?;
    validate(&table)?;
    Ok((render_typescript(&table)?, render_rust(&table)?))
}

fn validate(table: &RedactionTable) -> Result<(), Box<dyn std::error::Error>> {
    if table.version != 1 {
        return Err(format!("{REDACTION_JSON}: version {} is not 1", table.version).into());
    }
    if table.credential_names.is_empty() {
        return Err(format!("{REDACTION_JSON}: credential_names is empty").into());
    }
    let mut seen = BTreeSet::new();
    for name in &table.credential_names {
        let lower = name.to_ascii_lowercase();
        if name.is_empty()
            || lower != *name
            || !name
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
        {
            return Err(format!(
                "{REDACTION_JSON}: credential name {name:?} is not lowercase ASCII letters, digits, '-' or '_'"
            )
            .into());
        }
        if !seen.insert(lower) {
            return Err(
                format!("{REDACTION_JSON}: credential name {name:?} is listed twice").into(),
            );
        }
    }
    if table.known_extensions.is_empty() {
        return Err(format!("{REDACTION_JSON}: known_extensions is empty").into());
    }
    let mut seen = BTreeSet::new();
    for extension in &table.known_extensions {
        if extension.is_empty()
            || !extension
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit())
        {
            return Err(format!(
                "{REDACTION_JSON}: known extension {extension:?} is not lowercase ASCII letters or digits"
            )
            .into());
        }
        if !seen.insert(extension) {
            return Err(
                format!("{REDACTION_JSON}: known extension {extension:?} is listed twice").into(),
            );
        }
    }
    for token in [&table.tokens.redacted, &table.tokens.path] {
        if !(token.starts_with('<') && token.ends_with('>') && token.len() > 2) {
            return Err(format!("{REDACTION_JSON}: token {token:?} is not <name>").into());
        }
    }
    Ok(())
}

/// Each entry as a JSON string literal, valid in both TypeScript and Rust.
fn quoted(list: &[String]) -> Result<Vec<String>, serde_json::Error> {
    list.iter().map(serde_json::to_string).collect()
}

fn render_typescript(table: &RedactionTable) -> Result<String, Box<dyn std::error::Error>> {
    let mut out = String::from(
        "// Generated by `cargo run -p bindings-gen` from canopi-types/redaction.json. Do not edit by hand.\n\
         // The credential names, known extensions and tokens of the one TS redactor, failures/redact.ts (contracts §13, 2.1-M434).\n\n",
    );
    out.push_str(
        "/** Credential parameter and JSON key names, lowercase; matched case-insensitively. */\n",
    );
    out.push_str("export const CREDENTIAL_NAMES = [");
    let names = table
        .credential_names
        .iter()
        .map(serde_json::to_string)
        .collect::<Result<Vec<_>, _>>()?;
    out.push_str(&names.join(", "));
    out.push_str("] as const\n\n");
    writeln!(
        out,
        "/** The file types Canopi reads or writes, lowercase: a path's last word ending in one ends it before a `path: reason` colon. */\nexport const KNOWN_EXTENSIONS = [{}] as const\n",
        quoted(&table.known_extensions)?.join(", ")
    )?;
    writeln!(
        out,
        "/** What a credential's value becomes. */\nexport const REDACTED_TOKEN = {}\n",
        serde_json::to_string(&table.tokens.redacted)?
    )?;
    writeln!(
        out,
        "/** What a path outside every named folder becomes. */\nexport const PATH_TOKEN = {}",
        serde_json::to_string(&table.tokens.path)?
    )?;
    Ok(out)
}

fn render_rust(table: &RedactionTable) -> Result<String, Box<dyn std::error::Error>> {
    let mut out = String::from(
        "// Generated by `cargo run -p bindings-gen` from canopi-types/redaction.json. Do not edit by hand.\n\
         //! The credential names, known extensions and tokens of the Rust redactor (contracts §13, 2.1-M434).\n\n",
    );
    let names = table
        .credential_names
        .iter()
        .map(serde_json::to_string)
        .collect::<Result<Vec<_>, _>>()?;
    writeln!(
        out,
        "/// Credential parameter and JSON key names, lowercase; matched case-insensitively.\npub const CREDENTIAL_NAMES: [&str; {}] = [{}];\n",
        names.len(),
        names.join(", ")
    )?;
    let extensions = quoted(&table.known_extensions)?;
    writeln!(
        out,
        "/// The file types Canopi reads or writes, lowercase: a path's last word ending in one ends it\n/// before a `path: reason` colon.\npub const KNOWN_EXTENSIONS: [&str; {}] = [{}];\n",
        extensions.len(),
        extensions.join(", ")
    )?;
    writeln!(
        out,
        "/// What a credential's value becomes.\npub const REDACTED_TOKEN: &str = {};\n",
        serde_json::to_string(&table.tokens.redacted)?
    )?;
    writeln!(
        out,
        "/// What a path outside every named folder becomes.\npub const PATH_TOKEN: &str = {};",
        serde_json::to_string(&table.tokens.path)?
    )?;
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::render_redaction_table;
    use std::fs;

    fn render(json: &str) -> Result<(String, String), String> {
        let dir = std::env::temp_dir().join(format!(
            "canopi-redaction-table-{}-{}",
            std::process::id(),
            json.len()
        ));
        fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
        let path = dir.join("redaction.json");
        fs::write(&path, json).map_err(|e| e.to_string())?;
        let rendered = render_redaction_table(&path).map_err(|e| e.to_string());
        let _ = fs::remove_dir_all(&dir);
        rendered
    }

    #[test]
    fn the_repository_table_reaches_both_languages() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap()
            .to_path_buf();
        let (ts, rust) = render_redaction_table(&root.join(super::REDACTION_JSON)).unwrap();
        for name in ["key", "api-key", "api_key", "apikey", "session"] {
            assert!(
                ts.contains(&format!("\"{name}\"")),
                "{name} missing from TS"
            );
            assert!(
                rust.contains(&format!("\"{name}\"")),
                "{name} missing from Rust"
            );
        }
        assert!(ts.contains("export const REDACTED_TOKEN = \"<redacted>\""));
        assert!(rust.contains("pub const PATH_TOKEN: &str = \"<path>\";"));
        assert!(ts.contains("export const KNOWN_EXTENSIONS = [\"canopi\", "));
        assert!(rust.contains("pub const KNOWN_EXTENSIONS: [&str; "));
    }

    #[test]
    fn a_duplicate_or_uppercase_name_or_a_bare_token_is_refused() {
        let table = |names: &str, token: &str| {
            format!(
                r#"{{"$comment": "c", "version": 1, "credential_names": [{names}], "known_extensions": ["canopi"], "tokens": {{"redacted": "{token}", "path": "<path>"}}}}"#
            )
        };
        assert!(render(&table(r#""key", "key""#, "<redacted>")).is_err());
        assert!(render(&table(r#""Key""#, "<redacted>")).is_err());
        assert!(render(&table(r#""key""#, "redacted")).is_err());
        assert!(render(&table("", "<redacted>")).is_err());
        assert!(render(&table(r#""key""#, "<redacted>")).is_ok());
    }

    #[test]
    fn a_duplicate_dotted_or_uppercase_extension_is_refused() {
        let table = |extensions: &str| {
            format!(
                r#"{{"$comment": "c", "version": 1, "credential_names": ["key"], "known_extensions": [{extensions}], "tokens": {{"redacted": "<redacted>", "path": "<path>"}}}}"#
            )
        };
        assert!(render(&table(r#""tif", "tif""#)).is_err());
        assert!(render(&table(r#""TIF""#)).is_err());
        assert!(render(&table(r#"".tif""#)).is_err());
        assert!(render(&table("")).is_err());
        assert!(render(&table(r#""tif", "laz""#)).is_ok());
    }
}
