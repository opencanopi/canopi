pub(crate) fn render_settings_runtime() -> Result<String, Box<dyn std::error::Error>> {
    let default_settings =
        serde_json::to_string_pretty(&canopi_types::settings::Settings::default())?;
    let locales = serde_json::to_string_pretty(canopi_types::settings::Locale::ALL)?;
    let themes = serde_json::to_string_pretty(canopi_types::settings::Theme::ALL)?;
    let basemap_styles = serde_json::to_string_pretty(canopi_types::settings::BasemapStyle::ALL)?;
    let satellite_sources =
        serde_json::to_string_pretty(canopi_types::settings::SatelliteSource::ALL)?;
    let plant_labels = serde_json::to_string_pretty(canopi_types::settings::PlantLabels::ALL)?;
    let scroll_wheels = serde_json::to_string_pretty(canopi_types::settings::ScrollWheel::ALL)?;
    Ok(format!(
        "// Generated by `cargo run -p bindings-gen`. Do not edit by hand.\n\n\
         import type {{ BasemapStyle, Locale, PlantLabels, SatelliteSource, ScrollWheel, Settings, Theme }} from './contracts'\n\n\
         export const DEFAULT_SETTINGS = {default_settings} as const satisfies Settings\n\n\
         export const SETTINGS_LOCALES = {locales} as const satisfies readonly Locale[]\n\n\
         export const SETTINGS_THEMES = {themes} as const satisfies readonly Theme[]\n\n\
         export const SETTINGS_BASEMAP_STYLES = {basemap_styles} as const satisfies readonly BasemapStyle[]\n\n\
         export const SETTINGS_PLANT_LABELS = {plant_labels} as const satisfies readonly PlantLabels[]\n\n\
         export const SETTINGS_SATELLITE_SOURCES = {satellite_sources} as const satisfies readonly SatelliteSource[]\n\n\
         export const SETTINGS_SCROLL_WHEELS = {scroll_wheels} as const satisfies readonly ScrollWheel[]\n"
    ))
}
