// policy/adapters/advisories.ts: the OSV exception table (2.1-M204; ADR 0028 Updates, Advisories): policy/advisories.json
// generates osv-scanner.toml and is held to what OSV reports. Ported from scripts/advisories.py (2.1-Q261, 2.1-M349).
//
//   node policy/adapters/advisories.ts generate [--stdout] [--root <dir>]       write osv-scanner.toml (temp file, then rename)
//   node policy/adapters/advisories.ts check [--offline] [--event E] [--changed PATH...] [--summary FILE] [--today D] [--root <dir>]
//
// One exception table: each entry names an advisory id (or one of its aliases), its package, a reason, an `until` date
// and the upstream W row whose exit retires it (`upstream`, resolved by policy/upstream.json). `check` never writes: it
// fails when osv-scanner.toml differs from what the table generates, an entry has no W tag or has expired, an entry's id
// is no longer reported (stale), or OSV reports an advisory the table does not list.
//
// OSV output is read only through osv-scanner.mjs beside this file, the one normaliser, over its lockfiles (the app's
// and the iOS lane's Appium, 2.1-Q247) with no ignore list. Online, the database is fetched and a failed run is retried
// once; `--offline` reads only the cached database and fails at once without one.
//
// A new advisory prints a ready `bd create` line to the step summary. Drift (a new advisory, a stale entry, an expired
// entry: the database or the calendar moved) fails every run except a pull request that changes no lockfile, table or
// config (`--event pull_request` with `--changed` naming none of them): that PR did not bring it, so the main or weekly
// run fails instead. The table's own faults and a config differing from it fail every run. CI never runs bd itself
// (2.1-M197; design check 5c).
import { appendFileSync, existsSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { exec } from '../core/exec.mjs'
import { collect, LOCKFILES } from './osv-scanner.mjs'

const TABLE = 'policy/advisories.json'
const CONFIG = 'osv-scanner.toml'
const REPO_ROOT = fileURLToPath(new URL('../../', import.meta.url))
// A pull request changing one of these can bring drift: a dependency, an entry's id or date, or the config.
const DRIFT_SOURCES = [...LOCKFILES, TABLE, CONFIG]
const W_TAG = /^W[0-9]+$/u
/** A YYYY-MM-DD date the calendar holds: 2026-02-30 or a 13th month is none. */
function isDate(text: string): boolean {
  const time = /^[0-9]{4}-[0-9]{2}-[0-9]{2}$/u.test(text) ? Date.parse(`${text}T00:00:00Z`) : Number.NaN
  return !Number.isNaN(time) && new Date(time).toISOString().slice(0, 10) === text
}
const HEADER = `# Generated by node policy/adapters/advisories.ts generate from ${TABLE}; never edit by hand.\n`
  + '# osv-scanner reads it for direct runs; CI checks the table against an unfiltered scan.\n'

interface Entry {
  readonly [field: string]: unknown
}

interface Site {
  readonly rule: string
  readonly path: string
  readonly name: string
  readonly aliases?: readonly string[]
}

class Refused extends Error {}

function loadTable(root: string): Entry[] {
  let table: unknown
  try {
    table = JSON.parse(readFileSync(join(root, TABLE), 'utf8'))
  } catch (error) {
    throw new Refused(`${TABLE} cannot be read: ${(error as Error).message}`)
  }
  const entries = typeof table === 'object' && table !== null && !Array.isArray(table) ? (table as Entry)['advisories'] : undefined
  if (!Array.isArray(entries)) throw new Refused(`${TABLE} has no top-level advisories array`)
  return entries as Entry[]
}

/** [the table's own faults, its expired entries]: a date passing is drift, not a fault of the PR. */
function tableProblems(entries: readonly Entry[], today: string): [string[], string[]] {
  const problems: string[] = []
  const expired: string[] = []
  const seen = new Set<unknown>()
  for (const entry of entries) {
    const ident = String(entry['id'] ?? '<no id>')
    if (seen.has(ident)) problems.push(`${ident} is listed twice`)
    seen.add(ident)
    for (const field of ['id', 'package', 'reason']) {
      const value = entry[field]
      if (typeof value !== 'string' || !value.trim()) problems.push(`${ident} has no ${field}`)
    }
    if (!W_TAG.test(String(entry['upstream'] ?? ''))) problems.push(`${ident} has no upstream W tag (a W row whose exit retires it)`)
    const until = String(entry['until'] ?? '')
    if (!isDate(until)) problems.push(`${ident} has no until date (YYYY-MM-DD)`)
    else if (until < today) expired.push(`${ident} expired on ${until}: re-check ${String(entry['upstream'] ?? 'its W row')} and renew or fix it`)
  }
  return [problems, expired]
}

const tomlString = (value: string) => JSON.stringify(value)
const byCodePoint = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0)

function render(entries: readonly Entry[]): string {
  const blocks = [...entries].sort((a, b) => byCodePoint(String(a['id']), String(b['id']))).map((entry) => {
    const reason = `${String(entry['upstream'] ?? '')}: ${String(entry['package'] ?? '')}: ${String(entry['reason'] ?? '')}`
    return `[[IgnoredVulns]]\nid = ${tomlString(String(entry['id']))}\nignoreUntil = ${String(entry['until'])}T00:00:00Z\n`
      + `reason = ${tomlString(reason)}\n`
  })
  return HEADER + blocks.map((block) => `\n${block}`).join('')
}

/** Writes `text` to a temporary file beside `path`, then renames it over `path`: never written in place. */
function writeAtomic(path: string, text: string): void {
  const temp = join(resolve(path, '..'), `.${CONFIG}.${process.pid}.${Date.now()}`)
  try {
    writeFileSync(temp, text)
    renameSync(temp, path)
  } catch (error) {
    rmSync(temp, { force: true })
    throw error
  }
}

/** The adapter's sites; online, one failed run is retried once. */
function scan(root: string, offline: boolean): Site[] {
  const attempts = offline ? 1 : 2
  for (let attempt = 1; ; attempt += 1) {
    try {
      return collect({ root, paths: LOCKFILES, exec, offline })
    } catch (error) {
      const { code, message } = error as { code?: unknown, message: string }
      if (code === 'reporter-exit') throw new Refused(message)
      if (code !== 'tool-failed') throw error
      if (offline) throw new Refused(`no cached advisory database to scan offline (OSV_SCANNER_LOCAL_DB_CACHE_DIRECTORY): ${message}`)
      if (attempt === attempts) throw new Refused(`osv-scanner failed after one retry (OSV API or database download unreachable?): ${message}`)
    }
  }
}

const aliasesOf = (site: Site) => (site.aliases?.length ? site.aliases : [site.rule])

function beadLine(site: Site): string {
  const title = `Advisory ${site.rule} in ${site.name} (${site.path})`
  const description = `OSV reports ${aliasesOf(site).join(', ')} for ${site.name} in ${site.path}. Update the dependency, `
    + `or list the id in ${TABLE} with a reason, an until date and the upstream W row whose exit retires it.`
  return `bd create ${tomlString(title)} --type bug --priority 1 --labels advisories --description ${tomlString(description)}`
}

interface CheckArgs {
  readonly offline: boolean
  readonly event: string
  readonly changed: readonly string[]
  readonly summary?: string
  readonly today: string
}

function check(root: string, args: CheckArgs): number {
  const entries = loadTable(root)
  const [problems, drift] = tableProblems(entries, args.today)
  const config = join(root, CONFIG)
  if (!existsSync(config) || readFileSync(config, 'utf8') !== render(entries)) {
    problems.push(`${CONFIG} differs from what ${TABLE} generates: run node policy/adapters/advisories.ts generate`)
  }
  const sites = scan(root, args.offline)
  const listed = new Set(entries.map((entry) => String(entry['id'])))
  const reported = new Set(sites.flatMap(aliasesOf))
  for (const ident of [...listed].filter((id) => !reported.has(id)).sort(byCodePoint)) {
    drift.push(`${ident} is no longer reported: delete its entry from ${TABLE} and its W row's mention`)
  }
  const unlisted = sites.filter((site) => !aliasesOf(site).some((alias) => listed.has(alias)))
  drift.push(...unlisted.map((site) => `${site.rule} (${site.name} in ${site.path}) is not in ${TABLE}`))
  const lines = [...new Set(unlisted.map(beadLine))].sort(byCodePoint)
  if (lines.length && args.summary) {
    appendFileSync(args.summary, '### New OSV advisories\n\nFile each as a bead (CI never runs bd):\n\n'
      + lines.map((line) => `${line}\n`).join(''))
  }
  if (args.event !== 'pull_request' || args.changed.some((path) => DRIFT_SOURCES.includes(path))) {
    problems.push(...drift)
  } else if (drift.length) {
    process.stdout.write(`A pull request changing no lockfile, ${TABLE} or ${CONFIG} did not bring these; the main or weekly run fails on them:\n`
      + [...drift, ...lines].map((line) => `  ${line}\n`).join(''))
  }
  for (const problem of problems) process.stderr.write(`ERROR: ${problem}\n`)
  if (problems.length) return 1
  process.stdout.write(`Advisories: ${sites.length} reported site(s), every one listed in ${TABLE}; none stale or expired.\n`)
  return 0
}

const USAGE = 'usage: node policy/adapters/advisories.ts generate [--stdout] [--root <dir>]\n'
  + '       node policy/adapters/advisories.ts check [--offline] [--event E] [--changed PATH...] [--summary FILE] [--today YYYY-MM-DD] [--root <dir>]\n'

/** The local date as YYYY-MM-DD. */
const localToday = () => {
  const now = new Date()
  return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`
}

interface Parsed {
  readonly values: ReadonlyMap<string, string>
  readonly flags: ReadonlySet<string>
  readonly changed: readonly string[]
}

/** The options, flags and `--changed` paths of `command`'s arguments `rest`, or undefined when one is not its own. */
function parseArgs(command: string, rest: readonly string[]): Parsed | undefined {
  const values = new Map<string, string>()
  const flags = new Set<string>()
  const changed: string[] = []
  const options = command === 'generate' ? ['--root'] : ['--root', '--event', '--summary', '--today']
  const bare = command === 'generate' ? ['--stdout'] : ['--offline']
  for (let index = 0; index < rest.length; index += 1) {
    const arg = rest[index] ?? ''
    if (bare.includes(arg)) flags.add(arg)
    else if (options.includes(arg) && index + 1 < rest.length) values.set(arg, rest[++index] ?? '')
    else if (arg !== '--changed' || command !== 'check') return undefined
    else while (index + 1 < rest.length && !(rest[index + 1] ?? '').startsWith('--')) changed.push(rest[++index] ?? '')
  }
  return { values, flags, changed }
}

/** The exit code of the command line `argv`. */
function main(argv: readonly string[]): number {
  const [command = '', ...rest] = argv
  const parsed = command === 'generate' || command === 'check' ? parseArgs(command, rest) : undefined
  if (!parsed) {
    process.stderr.write(USAGE)
    return 2
  }
  const { values, flags, changed } = parsed
  const root = resolve(values.get('--root') ?? REPO_ROOT)
  try {
    if (command === 'generate') {
      const text = render(loadTable(root))
      if (flags.has('--stdout')) process.stdout.write(text)
      else writeAtomic(join(root, CONFIG), text)
      return 0
    }
    const today = values.get('--today') ?? localToday()
    if (!isDate(today)) throw new Refused(`--today ${today} is no YYYY-MM-DD date`)
    const summary = values.get('--summary')
    return check(root, { offline: flags.has('--offline'), event: values.get('--event') ?? 'push', changed, today,
      ...summary === undefined ? {} : { summary } })
  } catch (error) {
    if (!(error instanceof Refused)) throw error
    process.stderr.write(`ERROR: ${error.message}\n`)
    return 1
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2))
