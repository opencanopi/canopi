#!/usr/bin/env node
// policy/generate.mjs: the layer table's validator and, from it and the policy tables' rules rows, the generated tool
// configs (ADR 0022; 2.1-M20, 2.1-M185, 2.1-M191; Phase 0 F1a). The entry: it validates the table, reads the rows and
// calls each part under policy/generate/ (depcruise, ast-grep, knip, boundary-facts; one file each under 2.1-Q243's
// 600 lines).
//
// The layer table (policy/layers.json) gives every module path under desktop/web/src one layer, longest prefix wins.
// validateLayerTable() refuses, fail closed, anything the generated configs could not stand on:
//   table-missing     no policy/layers.json
//   table-unreadable  not JSON, not an object or no layers array
//   field             a top-level key other than $comment, version, layers, outside and packages (a `rules` key
//                     would register rows with check.mjs, 2.1-M222), or a row column outside its vocabulary
//                     (layer L0-L5 or test; rank only in L1 and L2; edition; status new; a phase rules.json lists,
//                     required with a destination or status new)
//   module-path       a path or destination that is not a relative module path (`..`, absolute, a backslash)
//   slash             a row or outside path whose trailing slash disagrees with the disk: a directory written
//                     without one, or a file with one, covers nothing and its parent row would silently win
//   ambiguous         two rows for one path (a trailing slash aside)
//   unassigned        a file under desktop/web/src that no row's path covers
//   gone              a row or outside path that does not exist, unless the row is status new
//   new-exists        a status new row whose path exists (drop the status)
//   rule-unregistered a package owner row whose rule id no policy table registers (check.mjs loadTableRules: the
//                     rules rows of every policy/*.json table, planned rows included, so a package rule not built yet
//                     is a planned row): it would generate a rule with no family, planted violation or owner
//   rule-file         an ast-grep rule file in a subdirectory of the rules directory, or whose id is not its file name
//                     (`<id>.yml`, or `<id>.<language>.yml` for a rule over several ast-grep languages, 2.1-M226) or
//                     names no active ast-grep row of a policy table
//   rule-message      an ast-grep rule file whose message lacks its row's owner_today and example (contracts §18)
//   rule-test         an ast-grep rule test whose id names no rule document: `ast-grep test` prints "Configuration not
//                     found!" and passes, so a deleted or renamed rule would leave its tests green
//   rule-graph        a rules row's `graph` spec with a key outside its vocabulary or a glob the generator cannot write
//                     as a dependency-cruiser regex (only `**`, `*`, `{a,b}` and literal text)
//   rule-path         a source or exemption glob (from, fromNot, toNot, typeOnlyTo) of a rules row's `graph` spec that matches no file under desktop/web/src: it
//                     would hold nothing (FAP's policy path drift, retired onto this refusal)
//   rule-members      the members a `# members:` rule spells (MEMBER_RULES) differ from its union (RasterQuantity in
//                     desktop/web/src/generated/contracts.ts, ToolId in the tool-id row's owner_today), or that union
//                     cannot be read
//   knip-ignore       a file under a generated-area row without a `// Generated by` first line: knip.json ignores those
//                     rows and .d.ts only (2.1-M218), so hand code there would never be reported
// Every code has a planted case under policy/fixtures/generate/, and `--self-test` fails a code without one.
//
//   node policy/generate.mjs              validate, then write each drifted generated file (OUTPUTS) by a temporary
//                                         file and a rename; nothing is written on a refusal; a rerun is byte-identical
//   node policy/generate.mjs --check      validate and exit 1 naming each drifted generated file; never writes
//   node policy/generate.mjs --self-test  run the planted cases and the write and check modes, hold the running
//                                         Node's prefix-free built-ins to NODE_BUILTINS, then this repository's tables
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { keyPath, loadTableRules } from './check.mjs';
import { AST_GREP_RULES, memberRefusals, primitiveRuleOutputs, ruleFileRefusals, ruleTestRefusals, sgconfigText } from './generate/ast-grep.mjs';
import { bare, buildFacts, filesUnder, isObject, LAYER_TABLE, REPO_ROOT, rowFor, SRC, WEB } from './generate/boundary-facts.mjs';
import { depcruiseConfigs, graphRefusals, unlistedBuiltins } from './generate/depcruise.mjs';
import { knipConfig, knipIgnoreRefusals, knipText } from './generate/knip.mjs';

export { LAYER_TABLE, REPO_ROOT, SRC };
const CASES_DIR = 'policy/fixtures/generate';

export const REFUSALS = {
  'table-missing': 'no layer table',
  'table-unreadable': 'a layer table that is not JSON, not an object or has no layers array',
  field: 'a top-level key or row column outside the table vocabulary',
  'module-path': 'a path or destination that is not a relative module path',
  slash: 'a path whose trailing slash disagrees with the disk (directories end in /, files do not)',
  ambiguous: 'two rows for one path',
  unassigned: 'a source file no row covers',
  gone: 'a row or outside path that does not exist and is not marked new',
  'new-exists': 'a row marked new whose path exists',
  'rule-unregistered': 'a package owner rule id no policy table registers',
  'rule-file': 'an ast-grep rule file in a subdirectory, or whose id is not its file name, its language suffix or an active policy table row',
  'rule-message': "an ast-grep rule file whose message lacks its row's owner_today and example",
  'rule-test': 'an ast-grep rule test whose id names no rule document',
  'rule-graph': "a rules row's graph spec with an unknown key or a glob the generator cannot translate",
  'rule-path': "a module glob of a rules row's graph spec that matches no source file",
  'rule-members': "the RasterQuantity rule's member list differs from the generated contract's union, or the union is unreadable",
  'knip-ignore': 'a generated-area row over a file without a `// Generated by` header (knip would ignore hand code)',
};

const TOP_KEYS = new Set(['$comment', 'version', 'layers', 'outside', 'packages']);
const ROW_KEYS = new Set(['path', 'layer', 'rank', 'destination', 'phase', 'edition', 'status', 'entry', 'area', 'owner', 'note']);
const OUTSIDE_KEYS = new Set(['path', 'edition', 'entry', 'role']);
const LAYERS = new Set(['L0', 'L1', 'L2', 'L3', 'L4', 'L5', 'test']);
const EDITIONS = new Set(['desktop', 'web', 'both', 'gallery']);
const PACKAGE_EDITIONS = new Set(['desktop', 'web']);
const PACKAGE_KEYS = new Set(['pattern', 'lowest_layer', 'owner', 'chunk', 'editions', 'rule', 'reason', 'note']);

/** A module path (one optional trailing slash) as check.mjs reads it, or undefined. */
const modulePath = (p) => (typeof p === 'string' && keyPath('path', bare(p)) !== undefined ? bare(p) : undefined);

/** A slash refusal message when `written` (as the table holds it) names an existing path of the other kind. */
function slashMismatch(full, written) {
  if (!fs.existsSync(full) || fs.statSync(full).isDirectory() === written.endsWith('/')) return undefined;
  return written.endsWith('/') ? `${written} is a file; drop the trailing slash` : `${written} is a directory; write it ${written}/`;
}

/** The plan's phase labels (policy/rules.json `phases`); the phase column takes only these. */
function phases() {
  try {
    return new Set(JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'policy/rules.json'), 'utf8')).phases);
  } catch {
    return new Set();
  }
}

/** Refusals ({code, where, message}) for the layer table under `root`. */
export function validateLayerTable(root = REPO_ROOT) {
  const where = LAYER_TABLE;
  const file = path.join(root, LAYER_TABLE);
  const refuse = (code, at, message) => ({ code, where: at, message });
  if (!fs.existsSync(file)) return [refuse('table-missing', where, 'the layer table is the one owner of the module layers (ADR 0022)')];
  let table;
  try {
    table = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (error) {
    return [refuse('table-unreadable', where, error.message)];
  }
  if (!isObject(table) || !Array.isArray(table.layers)) return [refuse('table-unreadable', where, 'no layers array')];

  const refusals = [];
  const known = phases();
  for (const key of Object.keys(table)) {
    if (!TOP_KEYS.has(key)) refusals.push(refuse('field', where, `top-level "${key}" is not a layer table key`));
  }
  const rows = [];
  const seen = new Map();
  table.layers.forEach((row, i) => {
    const at = `${where}#/layers/${i}`;
    if (!isObject(row)) return refusals.push(refuse('field', at, 'a row is an object'));
    const p = modulePath(row.path);
    if (p === undefined) return refusals.push(refuse('module-path', at, `path ${JSON.stringify(row.path)} is not a module path under ${SRC}`));
    for (const key of Object.keys(row)) if (!ROW_KEYS.has(key)) refusals.push(refuse('field', at, `"${key}" is not a row column`));
    if (!LAYERS.has(row.layer)) refusals.push(refuse('field', at, `layer ${JSON.stringify(row.layer)} is not one of ${[...LAYERS]}`));
    if (!EDITIONS.has(row.edition)) refusals.push(refuse('field', at, `edition ${JSON.stringify(row.edition)} is not one of ${[...EDITIONS]}`));
    if (row.rank !== undefined && !(['L1', 'L2'].includes(row.layer) && Number.isInteger(row.rank) && row.rank > 0)) {
      refusals.push(refuse('field', at, 'rank is a positive integer, in L1 and L2 only'));
    }
    if (row.status !== undefined && row.status !== 'new') refusals.push(refuse('field', at, 'status takes only "new"'));
    if (row.phase !== undefined && !known.has(row.phase)) refusals.push(refuse('field', at, `phase ${JSON.stringify(row.phase)} is not in policy/rules.json phases`));
    if ((row.destination !== undefined || row.status === 'new') && row.phase === undefined) {
      refusals.push(refuse('field', at, 'a destination or a new row names the phase that lands it'));
    }
    if (row.destination !== undefined && modulePath(row.destination) === undefined) {
      refusals.push(refuse('module-path', at, `destination ${JSON.stringify(row.destination)} is not a module path under ${SRC}`));
    }
    if (seen.has(p)) refusals.push(refuse('ambiguous', at, `${row.path} also has row ${seen.get(p)}`));
    else seen.set(p, i);
    const exists = fs.existsSync(path.join(root, SRC, p));
    const kind = slashMismatch(path.join(root, SRC, p), row.path);
    if (kind) refusals.push(refuse('slash', at, kind));
    if (row.status === 'new' && exists) refusals.push(refuse('new-exists', at, `${row.path} exists; drop status new`));
    if (row.status !== 'new' && !exists) refusals.push(refuse('gone', at, `${row.path} is not under ${SRC}; mark it new, give it a destination's row or delete the row`));
    rows.push(row);
  });
  (Array.isArray(table.outside) ? table.outside : []).forEach((row, i) => {
    const at = `${where}#/outside/${i}`;
    if (!isObject(row) || modulePath(row.path) === undefined) return refusals.push(refuse('module-path', at, `outside path is not a module path under ${WEB}`));
    for (const key of Object.keys(row)) if (!OUTSIDE_KEYS.has(key)) refusals.push(refuse('field', at, `"${key}" is not an outside column`));
    if (!EDITIONS.has(row.edition)) refusals.push(refuse('field', at, `edition ${JSON.stringify(row.edition)} is not one of ${[...EDITIONS]}`));
    if (!fs.existsSync(path.join(root, WEB, bare(row.path)))) refusals.push(refuse('gone', at, `${row.path} is not under ${WEB}`));
    const kind = slashMismatch(path.join(root, WEB, bare(row.path)), row.path);
    if (kind) refusals.push(refuse('slash', at, kind));
  });
  const tables = loadTableRules(root);
  const registered = new Set([...tables.rules.keys(), ...tables.planned.keys()]);
  (Array.isArray(table.packages) ? table.packages : []).forEach((row, i) => {
    const at = `${where}#/packages/${i}`;
    if (!isObject(row) || typeof row.pattern !== 'string' || !row.pattern) return refusals.push(refuse('field', at, 'a package row has a pattern'));
    for (const key of Object.keys(row)) if (!PACKAGE_KEYS.has(key)) refusals.push(refuse('field', at, `"${key}" is not a package column`));
    if ((row.owner === undefined) === (row.lowest_layer === undefined)) refusals.push(refuse('field', at, 'a package row names an owner or a lowest_layer, not both'));
    if (row.lowest_layer !== undefined && !LAYERS.has(row.lowest_layer)) refusals.push(refuse('field', at, `lowest_layer ${JSON.stringify(row.lowest_layer)} is not a layer`));
    if (row.owner !== undefined && row.rule === undefined) refusals.push(refuse('field', at, 'an owner row names the rule that holds it'));
    if (row.rule !== undefined && !registered.has(row.rule)) {
      refusals.push(refuse('rule-unregistered', at, `rule ${JSON.stringify(row.rule)} is no row of a policy table's rules (policy/rules.json, policy/primitives.json); add it, planned until its family lands`));
    }
    if (!Array.isArray(row.editions) || !row.editions.length || !row.editions.every((e) => PACKAGE_EDITIONS.has(e))) {
      refusals.push(refuse('field', at, 'editions lists desktop, web or both'));
    }
  });
  for (const f of filesUnder(path.join(root, SRC))) {
    if (!rowFor(rows, f)) refusals.push(refuse('unassigned', `${SRC}/${f}`, 'no layer table row covers it; add a row (ADR 0022: every path has one layer)'));
  }
  return refusals;
}


// ---------------------------------------------------------------------------------------------------------------
// Generation (contracts §12, §18; ADR 0022 Checks; 2.1-M185, 2.1-M218, 2.1-M221, 2.1-M226)
//
// From the layer table and the policy tables' rules rows, each output by its part under policy/generate/:
// dependency-cruiser's Desktop and Web configs (depcruise.mjs), ast-grep's one project config and the primitive rule
// files' messages and ignores (ast-grep.mjs), knip's config (knip.mjs) and the build facts (boundary-facts.mjs).

export const OUTPUTS = {
  desktop: 'desktop/web/.dependency-cruiser.cjs',
  web: 'desktop/web/.dependency-cruiser.web.cjs',
  sgconfig: 'sgconfig.yml',
  facts: 'desktop/web/build-facts.generated.json',
  knip: 'desktop/web/knip.json',
  knipPlanted: 'policy/fixtures/rules/knip/knip.json',
};

/** Active policy table rows by id (check.mjs reports the tables' own refusals). */
function activeRows(root) {
  const tables = loadTableRules(root);
  return new Map([...tables.rules].map(([id, { row }]) => [id, row]));
}

/** {refusals, outputs: {path: text}} for the repository under `root`: the outputs exist only when nothing is refused. */
export function generate(root = REPO_ROOT) {
  const refusals = validateLayerTable(root);
  if (refusals.some((r) => r.code.startsWith('table-'))) return { refusals, outputs: {} };
  const rows = activeRows(root);
  const table = JSON.parse(fs.readFileSync(path.join(root, LAYER_TABLE), 'utf8'));
  refusals.push(...ruleFileRefusals(root, rows), ...ruleTestRefusals(root), ...graphRefusals(root, rows), ...memberRefusals(root, rows), ...knipIgnoreRefusals(root, table));
  if (refusals.length) return { refusals, outputs: {} };
  const depcruise = depcruiseConfigs(table, rows);
  return {
    refusals,
    outputs: {
      [OUTPUTS.desktop]: depcruise.desktop,
      [OUTPUTS.web]: depcruise.web,
      [OUTPUTS.sgconfig]: sgconfigText(),
      [OUTPUTS.facts]: `${JSON.stringify(buildFacts(table), null, 2)}\n`,
      [OUTPUTS.knip]: knipConfig(table),
      [OUTPUTS.knipPlanted]: knipText({ entry: ['src/main.ts'], project: ['src/**'] }),
      ...primitiveRuleOutputs(root, table),
    },
  };
}

/** The outputs under `root` that differ from what generate() gives. */
export function drifted(root, outputs) {
  return Object.entries(outputs).filter(([rel, text]) => !fs.existsSync(path.join(root, rel)) || fs.readFileSync(path.join(root, rel), 'utf8') !== text).map(([rel]) => rel);
}

/** Writes each drifted output by a temporary file and a rename, so a reader never sees half a file. */
export function write(root, outputs) {
  for (const rel of drifted(root, outputs)) {
    const target = path.join(root, rel);
    const temp = `${target}.${process.pid}.tmp`;
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(temp, outputs[rel]);
    fs.renameSync(temp, target);
  }
}

// ---------------------------------------------------------------------------------------------------------------
// Self-test

/** Writes a case's files ({path: text or JSON value}) under a fresh temporary root. */
function plant(files) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'canopi-generate-'));
  // loadTableRules lists the repository's files with git, as in a checkout.
  execFileSync('git', ['init', '-q'], { cwd: root, stdio: 'ignore' });
  for (const [rel, content] of Object.entries(files)) {
    const target = path.join(root, rel);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, typeof content === 'string' ? content : JSON.stringify(content));
  }
  return root;
}

/**
 * Write and check modes over the valid case's tree: a write then a rerun is byte-identical; `--check` names a drifted
 * output and an output deleted, and writes nothing. Returns the failures.
 */
function checkModeCases(casesRoot, log) {
  const valid = path.join(casesRoot, 'valid.json');
  const root = plant(fs.existsSync(valid) ? JSON.parse(fs.readFileSync(valid, 'utf8')).files : {});
  const fail = (what) => { log(`FAIL check mode: ${what}`); return [`check mode: ${what}`]; };
  try {
    const { refusals, outputs } = generate(root);
    if (refusals.length || !Object.keys(outputs).length) return fail(`the valid case does not generate (${refusals.map((r) => r.code)})`);
    const absent = Object.values(OUTPUTS).filter((rel) => !(rel in outputs));
    if (absent.length) return fail(`the valid case generates no ${absent.join(', ')}`);
    write(root, outputs);
    const first = Object.fromEntries(Object.keys(outputs).map((rel) => [rel, fs.readFileSync(path.join(root, rel))]));
    write(root, generate(root).outputs);
    if (Object.entries(first).some(([rel, bytes]) => !bytes.equals(fs.readFileSync(path.join(root, rel))))) return fail('a rerun is not byte-identical');
    if (fs.readdirSync(path.join(root, 'desktop/web')).some((n) => n.endsWith('.tmp'))) return fail('a temporary file was left');
    const edited = OUTPUTS.desktop;
    fs.writeFileSync(path.join(root, edited), '// hand edit\n');
    fs.rmSync(path.join(root, OUTPUTS.facts));
    const named = drifted(root, generate(root).outputs);
    if (JSON.stringify(named.sort()) !== JSON.stringify([edited, OUTPUTS.facts].sort())) return fail(`--check names ${named}, not ${edited} and ${OUTPUTS.facts}`);
    if (fs.readFileSync(path.join(root, edited), 'utf8') !== '// hand edit\n' || fs.existsSync(path.join(root, OUTPUTS.facts))) return fail('--check wrote');
    log('ok   check mode: a rerun is byte-identical; --check names drift and writes nothing');
    return [];
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
}

/** Runs the planted cases, the write and check modes, then this repository's tables; returns {failures, missing}. */
export function selfTest(casesRoot = path.join(REPO_ROOT, CASES_DIR), log = () => {}) {
  const failures = [];
  const covered = new Set();
  for (const name of (fs.existsSync(casesRoot) ? fs.readdirSync(casesRoot) : []).sort()) {
    if (!name.endsWith('.json')) {
      log(`FAIL ${name}: a case is a .json file`);
      failures.push(name);
      continue;
    }
    const kase = JSON.parse(fs.readFileSync(path.join(casesRoot, name), 'utf8'));
    const expected = [...new Set(kase.expect)].sort();
    expected.forEach((code) => covered.add(code));
    const root = plant(kase.files ?? {});
    let got;
    try {
      // A `generate` case runs the whole generation (rule files included), others the table validator.
      got = [...new Set((kase.generate ? generate(root).refusals : validateLayerTable(root)).map((r) => r.code))].sort();
      // A `drifted` case names the rule files --check reports, and a write leaves none drifted.
      if (kase.drifted) {
        const ruleDrift = () => drifted(root, generate(root).outputs).filter((rel) => rel.startsWith(`${AST_GREP_RULES}/`)).sort();
        const before = ruleDrift();
        write(root, generate(root).outputs);
        const after = ruleDrift();
        if (JSON.stringify(before) !== JSON.stringify([...kase.drifted].sort()) || after.length) got.push(`drifted [${before}], after a write [${after}]`);
      }
    } catch (error) {
      got = [`threw: ${error.message}`];
    } finally {
      fs.rmSync(root, { recursive: true, force: true });
    }
    const ok = JSON.stringify(got) === JSON.stringify(expected);
    log(`${ok ? 'ok  ' : 'FAIL'} ${name}${ok ? '' : `: expected [${expected}], got [${got}]`}`);
    if (!ok) failures.push(name);
  }
  failures.push(...checkModeCases(casesRoot, log));
  const unlisted = unlistedBuiltins();
  log(`${unlisted.length ? 'FAIL' : 'ok  '} NODE_BUILTINS holds every prefix-free built-in of Node ${process.version}${unlisted.length ? `: add ${unlisted.join(', ')}` : ''}`);
  if (unlisted.length) failures.push('NODE_BUILTINS');
  const own = generate(REPO_ROOT);
  for (const r of own.refusals) log(`FAIL repository ${r.code}: ${r.where}: ${r.message}`);
  if (!own.refusals.length) log(`ok   ${LAYER_TABLE} validates and generates`);
  else failures.push(LAYER_TABLE);
  const missing = Object.keys(REFUSALS).filter((code) => !covered.has(code));
  return { failures, missing };
}

function main(argv) {
  if (argv.includes('--self-test')) {
    const { failures, missing } = selfTest(undefined, (line) => console.log(line));
    for (const code of missing) console.error(`${code} has no planted case under ${CASES_DIR}/`);
    console.log(failures.length || missing.length ? 'generate self-test: RED' : 'generate self-test: OK');
    return failures.length || missing.length ? 1 : 0;
  }
  const { refusals, outputs } = generate();
  for (const r of refusals) console.error(`${r.code}: ${r.where}: ${r.message}`);
  if (refusals.length) {
    console.log('generate: RED (nothing written)');
    return 1;
  }
  const stale = drifted(REPO_ROOT, outputs);
  if (argv.includes('--check')) {
    for (const rel of stale) console.error(`drifted: ${rel}; run node policy/generate.mjs`);
    console.log(`generate --check: ${stale.length ? 'RED' : 'OK'}`);
    return stale.length ? 1 : 0;
  }
  write(REPO_ROOT, outputs);
  console.log(`generate: ${stale.length ? `wrote ${stale.join(', ')}` : 'up to date'}`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
