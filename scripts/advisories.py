#!/usr/bin/env python3
"""The OSV exception table: policy/advisories.json generates osv-scanner.toml and is held to what OSV reports.

    python3 scripts/advisories.py generate [--stdout]      write osv-scanner.toml (temp file, then rename)
    python3 scripts/advisories.py check [--offline] [--event E] [--changed PATH...] [--summary FILE] [--today D]
    python3 -m unittest scripts.test_advisories

One exception table (2.1-M204): each entry names an advisory id (or one of its aliases), its package, a reason, an
`until` date and the upstream W row whose exit retires it (`upstream`, resolved by policy/upstream.json). `check`
never writes: it fails when osv-scanner.toml differs from what the table generates, an entry has no W tag or has
expired, an entry's id is no longer reported (stale), or OSV reports an advisory the table does not list.

OSV output is read only through policy/adapters/osv-scanner.mjs (its CLI), the one normaliser, which runs
osv-scanner over Cargo.lock and desktop/web/package-lock.json with no ignore list. Online, the database is fetched
and a failed run is retried once; `--offline` reads only the cached database and fails at once without one.

A new advisory prints a ready `bd create` line to the step summary. It fails every run except a pull request that
changes no lockfile (`--event pull_request` with `--changed` naming none): that PR did not bring it, so the main or
weekly run fails instead, and CI never runs bd itself (2.1-M197; design check 5c).
Stdlib, git-free; needs node for the adapter.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

REPO_ROOT = Path(__file__).resolve().parent.parent
TABLE = "policy/advisories.json"
CONFIG = "osv-scanner.toml"
ADAPTER = REPO_ROOT / "policy" / "adapters" / "osv-scanner.mjs"
LOCKFILES = ("Cargo.lock", "desktop/web/package-lock.json")
W_TAG = re.compile(r"W[0-9]+")
DATE = re.compile(r"[0-9]{4}-[0-9]{2}-[0-9]{2}")
HEADER = (f"# Generated by scripts/advisories.py generate from {TABLE}; never edit by hand.\n"
          "# osv-scanner reads it for direct runs; CI checks the table against an unfiltered scan.\n")


class Refused(Exception):
    pass


def load_table(root: Path) -> list[dict]:
    try:
        table = json.loads((root / TABLE).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise Refused(f"{TABLE} cannot be read: {error}") from error
    entries = table.get("advisories") if isinstance(table, dict) else None
    if not isinstance(entries, list):
        raise Refused(f"{TABLE} has no top-level advisories array")
    return entries


def table_problems(entries: list[dict], today: dt.date) -> list[str]:
    problems, seen = [], set()
    for entry in entries:
        ident = entry.get("id", "<no id>")
        if ident in seen:
            problems.append(f"{ident} is listed twice")
        seen.add(ident)
        for field in ("id", "package", "reason"):
            if not isinstance(entry.get(field), str) or not entry[field].strip():
                problems.append(f"{ident} has no {field}")
        if not W_TAG.fullmatch(str(entry.get("upstream", ""))):
            problems.append(f"{ident} has no upstream W tag (a W row whose exit retires it)")
        until = str(entry.get("until", ""))
        if not DATE.fullmatch(until):
            problems.append(f"{ident} has no until date (YYYY-MM-DD)")
        elif dt.date.fromisoformat(until) < today:
            problems.append(f"{ident} expired on {until}: re-check {entry.get('upstream', 'its W row')} and renew or "
                            "fix it")
    return problems


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(entries: list[dict]) -> str:
    blocks = []
    for entry in sorted(entries, key=lambda e: str(e.get("id"))):
        reason = f"{entry.get('upstream', '')}: {entry.get('package', '')}: {entry.get('reason', '')}"
        blocks.append(f"[[IgnoredVulns]]\nid = {toml_string(str(entry.get('id')))}\n"
                      f"ignoreUntil = {entry.get('until')}T00:00:00Z\nreason = {toml_string(reason)}\n")
    return HEADER + "".join(f"\n{block}" for block in blocks)


def write_atomic(path: Path, text: str) -> None:
    fd, temp = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        os.replace(temp, path)
    except BaseException:
        Path(temp).unlink(missing_ok=True)
        raise


def scan(root: Path, offline: bool) -> list[dict]:
    """The adapter's sites; online, one failed run is retried once."""
    command = ["node", str(ADAPTER), *(["--offline"] if offline else []), "--root", str(root), *LOCKFILES]
    attempts = 1 if offline else 2
    for attempt in range(1, attempts + 1):
        result = subprocess.run(command, capture_output=True, text=True, check=False)
        try:
            out = json.loads(result.stdout)
        except ValueError:
            raise Refused(f"the osv-scanner adapter failed: {result.stderr.strip() or result.stdout.strip()}")
        if "sites" in out:
            return out["sites"]
        if out.get("refusal") == "reporter-exit":
            raise Refused(out.get("message", "reporter-exit"))
        if offline:
            raise Refused(f"no cached advisory database to scan offline (OSV_SCANNER_LOCAL_DB_CACHE_DIRECTORY): "
                          f"{out.get('message')}")
        if attempt == attempts:
            raise Refused(f"osv-scanner failed after one retry (OSV API or database download unreachable?): "
                          f"{out.get('message')}")
    raise AssertionError("unreachable")


def bead_line(site: dict) -> str:
    title = f"Advisory {site['rule']} in {site['name']} ({site['path']})"
    description = (f"OSV reports {', '.join(site.get('aliases') or [site['rule']])} for {site['name']} in "
                   f"{site['path']}. Update the dependency, or list the id in {TABLE} with a reason, an until date "
                   "and the upstream W row whose exit retires it.")
    return f"bd create {toml_string(title)} --type bug --priority 1 --labels advisories --description {toml_string(description)}"


def check(root: Path, args: argparse.Namespace) -> int:
    today = dt.date.fromisoformat(args.today) if args.today else dt.date.today()
    entries = load_table(root)
    problems = table_problems(entries, today)
    config = root / CONFIG
    if not config.is_file() or config.read_text(encoding="utf-8") != render(entries):
        problems.append(f"{CONFIG} differs from what {TABLE} generates: run python3 scripts/advisories.py generate")
    sites = scan(root, args.offline)
    listed = {str(entry.get("id")) for entry in entries}
    reported = {alias for site in sites for alias in (site.get("aliases") or [site["rule"]])}
    for ident in sorted(listed - reported):
        problems.append(f"{ident} is no longer reported: delete its entry from {TABLE} and its W row's mention")
    unlisted = [site for site in sites if not listed & set(site.get("aliases") or [site["rule"]])]
    news = [f"{site['rule']} ({site['name']} in {site['path']}) is not in {TABLE}" for site in unlisted]
    lockfile_pr = args.event != "pull_request" or any(path in LOCKFILES for path in args.changed)
    if unlisted:
        lines = sorted({bead_line(site) for site in unlisted})
        if args.summary:
            with open(args.summary, "a", encoding="utf-8") as summary:
                summary.write("### New OSV advisories\n\nFile each as a bead (CI never runs bd):\n\n")
                summary.write("".join(f"{line}\n" for line in lines))
        if lockfile_pr:
            problems.extend(news)
        else:
            print("A pull request changing no lockfile did not bring these; the main or weekly run fails on them:")
            for line in news + lines:
                print(f"  {line}")
    for problem in problems:
        print(f"ERROR: {problem}", file=sys.stderr)
    if problems:
        return 1
    print(f"Advisories: {len(sites)} reported site(s), every one listed in {TABLE}; none stale or expired.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate", help=f"write {CONFIG} from {TABLE}")
    gen.add_argument("--stdout", action="store_true", help="print instead of writing")
    chk = sub.add_parser("check", help=f"hold {TABLE} and {CONFIG} to an unfiltered OSV scan; never writes")
    chk.add_argument("--offline", action="store_true", help="the cached database only, no retry")
    chk.add_argument("--event", default="push", help="the GitHub event (pull_request, push, schedule, ...)")
    chk.add_argument("--changed", nargs="*", default=[], help="a pull request's changed paths")
    chk.add_argument("--summary", help="append ready bd create lines here (GITHUB_STEP_SUMMARY)")
    chk.add_argument("--today", help="YYYY-MM-DD (tests)")
    for sp in (gen, chk):
        sp.add_argument("--root", type=Path, default=REPO_ROOT)
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        if args.command == "generate":
            text = render(load_table(root))
            if args.stdout:
                sys.stdout.write(text)
            else:
                write_atomic(root / CONFIG, text)
            return 0
        return check(root, args)
    except Refused as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
